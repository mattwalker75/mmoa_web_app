// config/localSecrets.js — machine-local secrets the app generates for itself.
//
// cookie-session signing keys never belonged in config.json: the committed
// config.json is cloned onto every server (mmoa_web_app_infra seds it into
// shape), so keys kept there would be shared by every install and visible in
// git. Instead they live in local-secrets.json next to config.json: generated
// once on first boot, mode 0600, gitignored, never written back into
// config.json. Losing the file logs everyone out — nothing worse.
//
// config.json's sessionKeys still win when they are real values, so a
// deployment that manages keys centrally keeps working unchanged.
//
// (The car-show control plane this is ported from also keeps a data key here
// for sealing short-lived secrets; this app has nothing to seal, so it only
// holds session keys.)

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const FILE = path.join(__dirname, '..', 'local-secrets.json');
let _cache = null;

function isPlaceholder(k) {
  return !k || typeof k !== 'string' || k.length < 16 || /^change-this/i.test(k) || /^<.*>$/.test(k);
}

function generate() {
  return {
    _comment: 'Generated by the Web App on first boot. Machine-local, gitignored. Deleting it signs every member out.',
    sessionKeys: [crypto.randomBytes(32).toString('hex'), crypto.randomBytes(32).toString('hex')],
    createdAt: new Date().toISOString()
  };
}

function load() {
  if (_cache) return _cache;
  let data = null;
  if (fs.existsSync(FILE)) {
    try { data = JSON.parse(fs.readFileSync(FILE, 'utf8')); }
    catch (e) { console.error('[secrets] local-secrets.json is unreadable — regenerating:', e.message); }
  }
  let dirty = false;
  if (!data || typeof data !== 'object') { data = generate(); dirty = true; }
  if (!Array.isArray(data.sessionKeys) || data.sessionKeys.length < 2 || data.sessionKeys.some(isPlaceholder)) {
    data.sessionKeys = generate().sessionKeys; dirty = true;
  }
  if (dirty) {
    try {
      fs.writeFileSync(FILE, JSON.stringify(data, null, 2) + '\n', { mode: 0o600 });
      try { fs.chmodSync(FILE, 0o600); } catch (_) { /* best effort */ }
      console.log('[secrets] wrote local-secrets.json (session keys)');
    } catch (e) {
      console.warn('[secrets] could not persist local-secrets.json — using in-memory keys for this boot:', e.message);
    }
  }
  _cache = data;
  return data;
}

// Session keys: config.json's if they are real, else the local file's.
function sessionKeys(appConfig) {
  const cfg = (appConfig && appConfig.sessionKeys) || [];
  if (cfg.length >= 2 && !cfg.slice(0, 2).some(isPlaceholder)) return { keys: cfg.slice(), source: 'config.json' };
  return { keys: load().sessionKeys, source: 'local-secrets.json' };
}

module.exports = { FILE, load, sessionKeys, isPlaceholder };
